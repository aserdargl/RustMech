"""Generate fused Rust formulas while preserving the NumPy expression tree."""

import ast
from pathlib import Path


def expression(node):
    if isinstance(node, ast.Constant):
        return repr(float(node.value))
    if isinstance(node, ast.BinOp):
        operator = {ast.Add: "+", ast.Sub: "-", ast.Mult: "*", ast.Div: "/"}[
            type(node.op)
        ]
        return f"({expression(node.left)} {operator} {expression(node.right)})"
    if isinstance(node, ast.UnaryOp) and isinstance(node.op, ast.USub):
        return f"(-{expression(node.operand)})"
    if isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute):
        prefix = {"sin": "s", "cos": "c"}[node.func.attr]
        arg = node.args[0]
        if isinstance(arg, ast.Name):
            return prefix + arg.id
        if (
            isinstance(arg, ast.BinOp)
            and isinstance(arg.left, ast.Constant)
            and arg.left.value == 2
        ):
            return prefix + "2" + arg.right.id
    raise ValueError(ast.dump(node))


root = Path(__file__).resolve().parents[1]
tree = ast.parse((root / "structure_library.py").read_text(encoding="utf-8"))
formulas = next(
    node.value
    for node in tree.body
    if isinstance(node, ast.AnnAssign) and node.target.id == "TPMS_FUNCTIONS"
)
lines = [
    "// Generated by tools/generate_tpms.py; preserve arithmetic order (no fast-math).",
    "pub fn evaluate<const KIND: u32>(axes: [[f64; 4]; 3]) -> f64 {",
    "    let [sx, cx, s2x, c2x] = axes[0];",
    "    let [sy, cy, s2y, c2y] = axes[1];",
    "    let [sz, cz, s2z, c2z] = axes[2];",
    "    match KIND {",
]
for index, formula in enumerate(formulas.values):
    lines.append(f"        {index} => {expression(formula.body)},")
lines.extend(["        _ => unreachable!(),", "    }", "}", ""])
(root / "native/mesh_kernel/src/tpms_generated.rs").write_text(
    "\n".join(lines), encoding="utf-8"
)
