"""CPU PyTorch regressors for rows, occupancy grids and voxel graphs."""

from copy import deepcopy

import numpy as np
import torch
from torch import nn


VOXELS = 24
SUBSAMPLES = 2


def occupancy(geometry):
    from mesh_engine import geometry_threshold
    from model import require_geometry, settings_from_dict
    from periodic_sampling import sample_box

    settings = settings_from_dict(geometry)
    require_geometry(settings, include_mesh=False)
    if settings.imported_geometry_path:
        raise ValueError("Spatial training requires geometry generated by RustMech.")
    fine = VOXELS * SUBSAMPLES
    axis = (np.arange(fine) + .5) / fine
    if settings.test_profile == "custom":
        field = sample_box(settings, [axis * size for size in settings.dimensions],
                           dtype=np.float32, threshold=geometry_threshold(settings))
    else:
        from standard_tests import profile, sample_shape

        field = sample_shape(settings, [axis * size for size in profile(settings).dimensions])
    solid = field <= 0
    grid = solid.reshape((VOXELS, SUBSAMPLES) * 3).sum(axis=(1, 3, 5), dtype=np.uint8)
    if not grid.any():
        raise ValueError("A generated geometry has no occupied voxels at the training resolution.")
    return grid


class VoxelGraph(nn.Module):
    """Mean message passing between face-adjacent occupied voxels."""

    def __init__(self):
        super().__init__()
        self.layers = nn.ModuleList((nn.Linear(8, 32), nn.Linear(64, 32), nn.Linear(64, 32)))

    def forward(self, grid):
        padded = nn.functional.pad(grid, (1, 1, 1, 1, 1, 1))
        positions = padded.nonzero()
        lookup = torch.full(padded.shape, -1, dtype=torch.long, device=grid.device)
        nodes = torch.arange(len(positions), device=grid.device)
        lookup[tuple(positions.T)] = nodes
        batch, x, y, z = positions.T
        neighbors = torch.stack((lookup[batch, x-1, y, z], lookup[batch, x+1, y, z],
                                 lookup[batch, x, y-1, z], lookup[batch, x, y+1, z],
                                 lookup[batch, x, y, z-1], lookup[batch, x, y, z+1]), dim=1)
        mask = neighbors >= 0
        source = neighbors[mask]
        destination = nodes[:, None].expand_as(neighbors)[mask]
        degree = mask.sum(dim=1, keepdim=True).clamp_min(1)
        coordinates = (positions[:, 1:].float() - .5) / VOXELS
        occupancy_fraction = padded[tuple(positions.T)].float()[:, None] / SUBSAMPLES**3
        features = torch.cat((coordinates, occupancy_fraction), dim=1)
        for layer in self.layers:
            messages = torch.zeros_like(features).index_add(0, destination, features[source])
            features = layer(torch.cat((features, messages / degree), dim=1)).relu()
        pooled = features.new_zeros((len(grid), 32)).index_add(0, batch, features)
        return pooled / torch.bincount(batch, minlength=len(grid)).clamp_min(1)[:, None]


class Regressor(nn.Module):
    def __init__(self, method, width):
        super().__init__()
        self.method = method
        if method == "cnn":
            self.encoder = nn.Sequential(nn.Conv3d(1, 8, 3, padding=1), nn.ReLU(), nn.MaxPool3d(2),
                                         nn.Conv3d(8, 16, 3, padding=1), nn.ReLU(),
                                         nn.AdaptiveAvgPool3d((2, 2, 2)), nn.Flatten())
            width += 128
        elif method == "gnn":
            self.encoder = VoxelGraph()
            width += 32
        self.head = nn.Sequential(nn.Linear(width, 64), nn.ReLU(), nn.Linear(64, 32), nn.ReLU(), nn.Linear(32, 1))

    def forward(self, values, grid):
        if self.method == "cnn":
            values = torch.cat((values, self.encoder(grid[:, None].float() / SUBSAMPLES**3)), dim=1)
        elif self.method == "gnn":
            values = torch.cat((values, self.encoder(grid)), dim=1)
        return self.head(values).squeeze(-1)


def fit_network(method, values, grids, y, train, validation, test, *, epochs, patience, progress):
    torch.manual_seed(42)
    model = Regressor(method, values.shape[1])
    values = torch.as_tensor(values, dtype=torch.float32)
    grid_tensor = torch.from_numpy(grids) if grids is not None else None
    scale = float(y[train].std()) or 1.
    mean = float(y[train].mean())
    target = torch.as_tensor((y - mean) / scale, dtype=torch.float32)
    optimizer = torch.optim.AdamW(model.parameters(), lr=.002)
    rng = np.random.default_rng(42)
    batch_size = 32 if method == "mlp" else 8

    def forward(index):
        return model(values[index], None if grid_tensor is None else grid_tensor[index])

    def predict(indices):
        model.eval()
        with torch.inference_mode():
            return torch.cat([forward(indices[i:i+batch_size])
                              for i in range(0, len(indices), batch_size)])

    history, best_loss, best_state, best_epoch = [], float("inf"), None, 0
    for epoch in range(1, epochs + 1):
        model.train()
        shuffled = rng.permutation(train)
        for start in range(0, len(shuffled), batch_size):
            batch = shuffled[start:start+batch_size]
            optimizer.zero_grad()
            loss = nn.functional.mse_loss(forward(batch), target[batch])
            loss.backward()
            optimizer.step()
        error = float(nn.functional.l1_loss(predict(validation), target[validation])) * scale
        if not np.isfinite(error):
            raise ValueError("The network diverged. Check input and target ranges.")
        history.append(error)
        progress(f"{method.upper()} · epoch {epoch}/{epochs} · validation MAE {error:.5g}")
        if error < best_loss:
            best_loss, best_epoch = error, epoch
            best_state = deepcopy(model.state_dict())
        if epoch - best_epoch >= patience:
            break
    model.load_state_dict(best_state)
    predictions = predict(test).numpy().astype(np.float64) * scale + mean
    checkpoint = dict(method=method, width=values.shape[1], voxels=VOXELS, subsamples=SUBSAMPLES,
                      weights=best_state, target_mean=mean, target_scale=scale)
    return checkpoint, predictions, {"best_epoch": best_epoch, "validation_mae_history": history}
